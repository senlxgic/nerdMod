// nerdMod: a tiny 5x7 pixel font for the home screen widgets (upper case, digits and a few symbols).
// Pure code, drawn into any RGB555 buffer with clipping; host-tested.
#pragma once

#include <stdint.h>
#include <string.h>

namespace nmfont {

inline const uint8_t *glyph(char c) {
	static const uint8_t G[][7] = {
		{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}, // space
		{0x00, 0x04, 0x04, 0x00, 0x04, 0x04, 0x00}, // :
		{0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C}, // .
		{0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00}, // -
		{0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10}, // /
		{0x18, 0x19, 0x02, 0x04, 0x08, 0x13, 0x03}, // %
		{0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00}, // +
		{0x06, 0x09, 0x09, 0x06, 0x00, 0x00, 0x00}, // degree sign
		{0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}, // 0
		{0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E}, // 1
		{0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}, // 2
		{0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E}, // 3
		{0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}, // 4
		{0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E}, // 5
		{0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E}, // 6
		{0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}, // 7
		{0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}, // 8
		{0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C}, // 9
		{0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, // A
		{0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E}, // B
		{0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E}, // C
		{0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E}, // D
		{0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F}, // E
		{0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10}, // F
		{0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F}, // G
		{0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, // H
		{0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E}, // I
		{0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C}, // J
		{0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11}, // K
		{0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F}, // L
		{0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11}, // M
		{0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11}, // N
		{0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, // O
		{0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10}, // P
		{0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D}, // Q
		{0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11}, // R
		{0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E}, // S
		{0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04}, // T
		{0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, // U
		{0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04}, // V
		{0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A}, // W
		{0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11}, // X
		{0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04}, // Y
		{0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F}, // Z
	};
	if (c >= 'a' && c <= 'z')
		c = (char)(c - 'a' + 'A');
	if (c >= 'A' && c <= 'Z')
		return G[18 + (c - 'A')];
	if (c >= '0' && c <= '9')
		return G[8 + (c - '0')];
	switch (c) {
		case ' ': return G[0];
		case ':': return G[1];
		case '.': return G[2];
		case '-': return G[3];
		case '/': return G[4];
		case '%': return G[5];
		case '+': return G[6];
		case '\xB0': return G[7];
		default: return nullptr; // unknown characters are skipped (drawn as a blank)
	}
}

inline int textWidth(const char *s, int scale) {
	const int n = (int)strlen(s);
	return n ? n * 6 * scale - scale : 0;
}

// Draws `s` with its top-left corner at (x, y) into a bw x bh RGB555 buffer; pixels outside are clipped.
inline void draw(uint16_t *buf, int bw, int bh, int x, int y, const char *s, int scale, uint16_t colour) {
	for (; *s; s++, x += 6 * scale) {
		const uint8_t *g = glyph(*s);
		if (!g)
			continue;
		for (int row = 0; row < 7; row++)
			for (int col = 0; col < 5; col++)
				if (g[row] & (0x10 >> col))
					for (int dy = 0; dy < scale; dy++)
						for (int dx = 0; dx < scale; dx++) {
							const int px = x + col * scale + dx, py = y + row * scale + dy;
							if (px >= 0 && py >= 0 && px < bw && py < bh)
								buf[py * bw + px] = colour;
						}
	}
}

inline void drawCentred(uint16_t *buf, int bw, int bh, int y, const char *s, int scale, uint16_t colour) {
	draw(buf, bw, bh, (bw - textWidth(s, scale)) / 2, y, s, scale, colour);
}

} // namespace nmfont
